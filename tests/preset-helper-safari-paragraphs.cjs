const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const root = 'tavern-helper/预设助手/';
function load(name, globals = {}, suffix = '') {
  const c = { exports: {}, console, setTimeout, clearTimeout, ...globals };
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(root + name + '.ts', 'utf8') + suffix, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, c);
  return c.exports;
}
(async () => {
  const dom = new JSDOM('<head></head><body style="transform:translateZ(0);overflow:hidden"><div id="extensionsMenu"></div></body>', { url: 'https://tavern.test', pretendToBeVisual: true });
  const w = dom.window;
  Object.defineProperty(w, 'innerWidth', { value: 390, configurable: true });
  Object.defineProperty(w, 'innerHeight', { value: 800, configurable: true });
  const vv = new w.EventTarget(); Object.assign(vv, { width: 390, height: 800, offsetTop: 1200, offsetLeft: 1500 });
  Object.defineProperty(w, 'visualViewport', { value: vv });
  Object.defineProperty(w, 'localStorage', { get() { throw new Error('storage blocked'); } });
  const api = load('bootstrap', { window: w, document: w.document, MutationObserver: w.MutationObserver, require: () => ({ floatingIcons: { test: { url: 'icon.png' }, other: { url: 'other.png' } }, normalizeFloatingIcon: value => value || 'test' }) });
  let opens = 0;
  const controller = api.registerHostEntries({ showPanel: async () => { opens++; }, hidePanel() {}, isPanelVisible: () => false });
  controller.sync({ floatingBall: true, extensionsMenu: true });
  const id = 'preset-helper-floating-entry';
  let ball = w.document.getElementById(id);
  assert.equal(ball.parentElement, w.document.documentElement, 'entry avoids transformed body');
  const visible = () => { ball = w.document.getElementById(id); assert.ok(parseFloat(ball.style.left) < 390); assert.ok(parseFloat(ball.style.top) < 800); };
  visible();
  ball.click(); await Promise.resolve(); assert.equal(opens, 1);
  const image = ball.querySelector('img'), fallback = ball.querySelector('span');
  image.dispatchEvent(new w.Event('load')); assert.equal(fallback.hidden, true);
  controller.sync({ floatingBall: true, extensionsMenu: true, floatingIcon: 'other' });
  assert.equal(fallback.hidden, false, 'fallback restored while replacement loads');
  image.dispatchEvent(new w.Event('error')); assert.equal(fallback.hidden, false);
  image.dispatchEvent(new w.Event('load')); assert.equal(image.style.visibility, '');
  vv.height = 300; vv.offsetTop = 0; vv.dispatchEvent(new w.Event('resize'));
  await new Promise(resolve => setTimeout(resolve, 30)); assert.ok(parseFloat(ball.style.top) <= 244);
  vv.height = 800; vv.offsetTop = NaN; vv.offsetLeft = Infinity;
  w.dispatchEvent(new w.Event('orientationchange'));
  await new Promise(resolve => setTimeout(resolve, 340)); visible();
  ball.remove(); await new Promise(resolve => setTimeout(resolve, 10)); visible();
  w.document.getElementById('preset-helper-floating-entry-style').remove();
  await new Promise(resolve => setTimeout(resolve, 10)); assert.ok(w.document.getElementById('preset-helper-floating-entry-style'));
  controller.destroy();
  w.dispatchEvent(new w.Event('pageshow')); await new Promise(resolve => setTimeout(resolve, 340));
  assert.equal(w.document.getElementById(id), null); dom.window.close();
  const constants = load('constants', { getScriptId: () => 'test', require: () => ({ DEFAULT_NSFW_SETTINGS: { openKeywords: [], closeKeywords: [], worldbookMarkers: [] } }) });
  const migration = load('paragraphPrompts', { require: () => constants }, '\nexports.legacy = legacyParagraphCommands;');
  const old = { ...migration.legacy }; migration.migrateParagraphCommands(old);
  for (const key of Object.keys(migration.legacy)) assert.equal(old[key], constants.defaultCommands[key]);
  const customized = { ...migration.legacy, paragraph_patch_short: '自己定制的 10-30 字短段' };
  migration.migrateParagraphCommands(customized); assert.equal(customized.paragraph_patch_short, '自己定制的 10-30 字短段');
  console.log('PASS: viewport/storage/image/recovery compatibility and paragraph default migration preserving custom prompts');
})().catch(e => { console.error(e); process.exitCode = 1; });
